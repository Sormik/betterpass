  Password generator profiles in the style of well-known password
  managers and browsers. They are ordinary KeePass profiles:
  - Apple uses the BetterPass syllable generator (custom algorithm),
    because KeePass' own generators cannot place exactly one uppercase
    letter at a random position inside fixed groups.
  - All others are KeePass pattern profiles ("Generate using pattern",
    "Randomly permute characters of password"). The pattern guarantees
    at least one character of every class. They keep working without
    BetterPass and can be changed in KeePass' own generator dialog.

  The formats follow what each generator visibly produces (length,
  character classes, grouping). They are not copies of vendor code.
*/

using System;
using System.Collections.Generic;
using System.Text;

using KeePass.App.Configuration;
using KeePass.Util;

using KeePassLib.Cryptography.PasswordGenerator;

namespace BetterPass
{
	internal static class PwProfiles
	{
		private const string NamePrefix = "BetterPass: ";
		public const string AppleName = NamePrefix + "Apple (Safari, iCloud-Schl\u00fcsselbund)";

		public static List<PwProfile> CreateAll()
		{
			List<PwProfile> l = new List<PwProfile>();
			l.Add(CreateApple(new PwStyle()));

			// 15 characters, letters and digits, no look-alikes
			l.Add(CreatePattern("Google Chrome", 15, null, true));
			// 15 characters including symbols
			l.Add(CreatePattern("Microsoft Edge", 15, "!#$%&*+-=?@^_", false));
			// 15 characters including symbols, no look-alikes
			l.Add(CreatePattern("Mozilla Firefox", 15, "-~!@#$%^&*_+=)}:;\"'>,.?]", true));
			// 20 characters including symbols
			l.Add(CreatePattern("1Password", 20, "!#$%&*+-.:=?@^_~", false));
			// 14 characters, letters and digits
			l.Add(CreatePattern("Bitwarden", 14, null, false));

			return l;
		}

		public static PwProfile CreateApple(PwStyle s)
		{
			PwProfile prf = new PwProfile();
			prf.Name = AppleName;
			prf.GeneratorType = PasswordGeneratorType.Custom;
			prf.CustomAlgorithmUuid = BpPwGenerator.GeneratorUuidString;
			prf.CustomAlgorithmOptions = s.Serialize();
			prf.CollectUserEntropy = false;
			return prf;
		}

		// One uppercase letter, one lowercase letter, one digit (and one
		// symbol), the rest from all classes; then shuffled by KeePass
		private static PwProfile CreatePattern(string strName, int nLength, string strSymbols,
			bool bExcludeLookAlike)
		{
			StringBuilder sb = new StringBuilder("uld");
			int nRest = nLength - 3;
			if(!string.IsNullOrEmpty(strSymbols))
			{
				string strEsc = EscapeForPattern(strSymbols);
				sb.Append('[').Append(strEsc).Append(']');
				sb.Append("[A").Append(strEsc).Append(']');
				--nRest;
			}
			else sb.Append('A');
			sb.Append('{').Append(nRest).Append('}');

			PwProfile prf = new PwProfile();
			prf.Name = NamePrefix + strName;
			prf.GeneratorType = PasswordGeneratorType.Pattern;
			prf.Pattern = sb.ToString();
			prf.PatternPermutePassword = true;
			prf.Length = (uint)nLength;
			prf.ExcludeLookAlike = bExcludeLookAlike;
			prf.CollectUserEntropy = false;
			return prf;
		}

		// In KeePass patterns, "\" makes the next character literal
		private static string EscapeForPattern(string str)
		{
			StringBuilder sb = new StringBuilder();
			foreach(char ch in str) sb.Append('\\').Append(ch);
			return sb.ToString();
		}

		// ===================== Installation =====================

		/// <summary>
		/// On the first start with this feature: adds the profiles and makes
		/// Apple the default for new entries.
		/// Later changes by the user (deleted profiles, other default) are
		/// left alone.
		/// </summary>
		public static void InstallOnce()
		{
			if(BpConfig.PwGenProfilesInstalled) return;

			AddMissing();

			AcePasswordGenerator cfg = KeePass.Program.Config.PasswordGenerator;
			PwProfile prfApple = FindUserProfile(AppleName);
			if(prfApple != null) cfg.AutoGeneratedPasswordsProfile = prfApple.CloneDeep();

			BpConfig.PwGenProfilesInstalled = true;
		}

		/// <summary>
		/// Adds every BetterPass profile that is missing (by name).
		/// Returns the number of added profiles.
		/// </summary>
		public static int AddMissing()
		{
			List<PwProfile> lUser = KeePass.Program.Config.PasswordGenerator.UserProfiles;
			int n = 0;
			foreach(PwProfile prf in CreateAll())
			{
				if(FindUserProfile(prf.Name) != null) continue;
				lUser.Add(prf);
				++n;
			}
			return n;
		}

		public static PwProfile FindUserProfile(string strName)
		{
			foreach(PwProfile prf in KeePass.Program.Config.PasswordGenerator.UserProfiles)
			{
				if((prf != null) && (prf.Name == strName)) return prf;
			}
			return null;
		}

		/// <summary>
		/// All profiles KeePass offers (built-in and user-defined), sorted.
		/// </summary>
		public static List<PwProfile> GetAll()
		{
			return PwGeneratorUtil.GetAllProfiles(true);
		}

		public static bool IsBetterPassSyllable(PwProfile prf)
		{
			return ((prf != null) && (prf.GeneratorType == PasswordGeneratorType.Custom) &&
				(prf.CustomAlgorithmUuid == BpPwGenerator.GeneratorUuidString));
		}

		/// <summary>
		/// True if both profiles generate the same kind of password
		/// (the name is ignored).
		/// </summary>
		public static bool SameSettings(PwProfile a, PwProfile b)
		{
			if((a == null) || (b == null)) return false;
			PwProfile c = b.CloneDeep();
			c.Name = a.Name;
			return a.Equals(c);
		}
	}
}
